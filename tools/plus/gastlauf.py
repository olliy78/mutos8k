"""Guest run with source disk change (plan 47 P1.0).

Like gast_as.gast_befehle, but the source drive D (/mnt) can be fed from several disks one after the other:
the step ("wechsel", i) unmounts /mnt in the guest, swaps the disk in the debugger and mounts disk i again.
Work disk A (/tmp) stays mounted and carries objects and results.  All images are COPIES in the work folder.

Exit 77 (skip) when the emulator is missing: callers catch gast_as.Fehlt.
"""
import os
import shutil
import subprocess
import sys
import time

HIER = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HIER), "kernel"))
sys.path.insert(0, os.path.dirname(HIER))
import emu  # noqa: E402
import gast_as  # noqa: E402

MTIME_1987 = "536457600"
Fehlt = gast_as.Fehlt


def _marker(z, text, nr, frist):
    z.append('gscreen "END%d" %d' % (nr, frist))
    z.append("g 4000000")       # type on only after the prompt (gscreen fires at the marker already)


def skript(arbeit, disketten, befehle, frist, schirm=False):
    """Debugger script.  Returns (script text, number of markers)."""
    z = ["# generated by tools/plus/gastlauf.py -- do not edit by hand",
         "g 80000000", "keys BOOT\\sMUTOS\\r", "g 100000000", "eject A",
         "mount A %s/tmp.hfe udos_ss77" % arbeit, "mount B %s/usr.hfe udos_ss77" % arbeit,
         "mount C %s/root.hfe udos_ss77" % arbeit, "mount D %s/d0.hfe udos_ss77" % arbeit,
         "keys r", "g 100000000", "keys root\\r", "g 100000000",
         "keys /etc/mount\\s/dev/rk1\\s/usr\\r", "g 30000000",
         "keys /etc/mount\\s/dev/rk3\\s/mnt\\r", "g 30000000",
         "keys /etc/mount\\s/dev/rk0\\s/tmp\\r", "g 30000000",
         "keys cd\\s/mnt\\r", "g 26000000",
         "keys PATH=/bin:/usr/bin:.\\r", "g 26000000"]
    nr = 0
    for b in befehle:
        nr += 1
        if isinstance(b, tuple):
            i = b[1]
            # the marker file of this step lives on A (the source disk is gone after umount)
            z.append("keys cd\\s/;/etc/umount\\s/dev/rk3;cat\\s/tmp/fertig%d\\r" % nr)
            _marker(z, "", nr, frist)
            z.append("eject D")
            z.append("mount D %s/d%d.hfe udos_ss77" % (arbeit, i))
            nr += 1
            z.append("keys /etc/mount\\s/dev/rk3\\s/mnt;cd\\s/mnt;cat\\sfertig%d\\r" % nr)
            _marker(z, "", nr, frist)
        else:
            z.append("keys %s;cat\\sfertig%d\\r" % (b.replace(" ", "\\s"), nr))
            _marker(z, "", nr, frist)
    z.append("keys cd\\s/;sync;cat\\s/tmp/fertigs\\r")
    z.append('gscreen "ENDES" 300000000')
    z.append("g 60000000")
    if schirm:
        z.append("screen")
    z.append("q")
    return "\n".join(z) + "\n", nr


def _put(img, pfade):
    for i in range(0, len(pfade), 20):
        rc, o = gast_as._lauf([gast_as.disktool(), "put", img] + pfade[i:i + 20])
        if rc:
            raise RuntimeError("put: " + o)


def _create(img, inodes):
    if os.path.exists(img):
        os.remove(img)
    rc, o = gast_as._lauf([gast_as.disktool(), "create", img, "--fs", "mutos8k_26x128_mfm", "--inodes", str(inodes)])
    if rc:
        raise RuntimeError("create %s: %s" % (img, o))


def lauf(arbeit, disketten, befehle, rueck, boot_hfe=None, ausfuehrbar=(), frist=3_000_000_000, ausgabe=None, schirm=False):
    """disketten: list of {name: bytes|str}, one source disk each (disk 0 is mounted first).
    befehle: shell command strings or ("wechsel", i).  rueck: names to fetch from /tmp.  Returns {name: bytes|None}.
    ausfuehrbar: names (on any disk) that get mode 0755.  Every file gets mtime 1987."""
    gast_as.pruefe_hilfsmittel()
    arbeit = os.path.abspath(arbeit)
    os.makedirs(arbeit, exist_ok=True)
    for ziel, quelle in gast_as.PLATTEN.items():
        shutil.copyfile(gast_as.disk(quelle), os.path.join(arbeit, ziel))
    if boot_hfe:
        shutil.copyfile(boot_hfe, os.path.join(arbeit, "boot.hfe"))
    nmark = sum(2 if isinstance(b, tuple) else 1 for b in befehle)
    # work disk A: markers of the change steps + the final one
    qa = os.path.join(arbeit, "qa")
    shutil.rmtree(qa, ignore_errors=True)
    os.makedirs(qa)
    with open(os.path.join(qa, "fertigs"), "w") as f:
        f.write("ENDES\n")
    nr = 0
    for b in befehle:
        nr += 1
        if isinstance(b, tuple):
            with open(os.path.join(qa, "fertig%d" % nr), "w") as f:
                f.write("END%d\n" % nr)
            nr += 1
        # all other markers are on the source disks
    tmp = os.path.join(arbeit, "tmp.hfe")
    _create(tmp, 200)
    _put(tmp, [os.path.join(qa, f) for f in sorted(os.listdir(qa))])
    for k, d in enumerate(disketten):
        q = os.path.join(arbeit, "q%d" % k)
        shutil.rmtree(q, ignore_errors=True)
        os.makedirs(q)
        for n, t in d.items():
            with open(os.path.join(q, n), "wb") as f:
                f.write(t if isinstance(t, bytes) else t.encode("latin-1"))
        for i in range(1, nmark + 1):
            with open(os.path.join(q, "fertig%d" % i), "w") as f:
                f.write("END%d\n" % i)
        names = sorted(os.listdir(q))
        img = os.path.join(arbeit, "d%d.hfe" % k)
        _create(img, len(names) + 40)
        _put(img, [os.path.join(q, f) for f in names if not f.endswith(".fileinfo")])
        for n in names:
            if n.endswith(".fileinfo"):
                continue
            args = ["--mtime", MTIME_1987] + (["--mode", "0755"] if n in ausfuehrbar else [])
            gast_as._lauf([gast_as.disktool(), "attr", img, n] + args)
    sk, _ = skript(arbeit, disketten, befehle, frist, schirm)
    skf = os.path.join(arbeit, "lauf.dbg")
    with open(skf, "w") as f:
        f.write(sk)
    log = os.path.join(arbeit, "lauf.log")
    t0 = time.time()
    with open(log, "w") as lf:
        subprocess.run(emu.tool_cmd("k1520dbg") + ["--rw", "--em", "em256", "--laufwerke", "K5601,K5601,K5601,K5601",
                       os.path.join(arbeit, "boot.hfe"), "-x", skf], stdout=lf, stderr=subprocess.STDOUT, cwd=gast_as.WURZEL)
    if ausgabe is not None:
        ausgabe["dauer"] = time.time() - t0
        ausgabe["log"] = log
    holen = os.path.join(arbeit, "zurueck")
    shutil.rmtree(holen, ignore_errors=True)
    os.makedirs(holen)
    erg = {}
    for n in rueck:
        gast_as._lauf([gast_as.disktool(), "get", tmp, n, "--to", holen])
        pf = os.path.join(holen, n)
        erg[n] = open(pf, "rb").read() if os.path.exists(pf) else None
    return erg


def probe(arbeit):
    """P1.0 acceptance run: two disks, change in between."""
    ausg = {}
    erg = lauf(arbeit, [{"a.txt": "AAA\n"}, {"b.txt": "BBB\n"}],
               ["cat a.txt >/tmp/a", ("wechsel", 1), "cat b.txt >/tmp/b", "ls /mnt >/tmp/l"],
               ["a", "b", "l"], ausgabe=ausg, schirm=True)
    print("Laufzeit %.0f s, Protokoll %s" % (ausg["dauer"], ausg["log"]))
    for n, v in erg.items():
        print("---", n, repr(v))
    l = (erg["l"] or b"").decode("latin-1").split()
    ok = erg["a"] == b"AAA\n" and erg["b"] == b"BBB\n" and "b.txt" in l and "a.txt" not in l
    print("ABNAHME", "ja" if ok else "NEIN")
    return 0 if ok else 1


if __name__ == "__main__":
    try:
        sys.exit(probe(sys.argv[1] if len(sys.argv) > 1 else "/tmp/mplus/p1_0"))
    except Fehlt as e:
        print("skip: missing", e)
        sys.exit(77)
