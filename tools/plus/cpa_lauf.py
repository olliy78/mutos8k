#!/usr/bin/env python3
"""Guest run tool over CP/A (plan 48 C5.1): the counterpart of tools/plus/gastlauf.py for the MUTOS CP/A variant.

The guest is started from the CP/A boot disk (cpa_disk.bootdiskette: 4-floppy CP/A + M8KBOOT.COM + MUTOS.SYS + MUTOSIO.IMG).  Prelude:
boot to `A>`, `M8KBOOT`, wait for the control mask (`ready (r)`), swap in the MUTOS disks (A /tmp, B /usr, C root, D /mnt), `r`, wait
for `login:`.  From `keys root` on, the script is the one of gastlauf.skript (cut out at an anchor), so markers, mounts and the
disk change steps are identical to the UDOS way.  End of file in the guest is ^Z (kernel/h/tty.h CEOT), see doc/plus/cpa/c3_4_tastatur.md.

API (same parameters/returns as the UDOS tools):
  skript(arbeit, disketten, befehle, frist, schirm=False) -> (script text, number of markers)   like gastlauf.skript
  lauf(arbeit, disketten, befehle, rueck, boot_hfe=None, ausfuehrbar=(), frist=..., ausgabe=None, schirm=False) -> {name: bytes|None}
        like gastlauf.lauf; boot_hfe = a CP/A boot disk (default: cpa_disk.bootdiskette(arbeit) with the original kernel)
  gast_befehle(arbeit, quellen, befehle, rueck, frist=..., ausgabe=None, boot_hfe=None, schirm=False, ausfuehrbar=(), ...)
        like gast_as.gast_befehle: one source disk D (/mnt)
  boot(arbeit, kernel_bytes) -> bool      boot the kernel over CP/A, run gastbau.TESTS, judge with gastbau.auswerten
  probe(arbeit) -> exit code              plan 47 P1.0 acceptance (cat a.txt, disk change, cat b.txt, ls /mnt)
Command line: cpa_lauf.py probe|boot --arbeit DIR [--kernel FILE].  Exit 77 without emulator/Workbench/tool chain.
All disk images live in <arbeit> as copies.
"""
import argparse
import os
import shutil
import subprocess
import sys
import time

HIER = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HIER)
sys.path.insert(0, os.path.dirname(HIER))
sys.path.insert(0, os.path.join(os.path.dirname(HIER), "kernel"))
import cpa  # noqa: E402
import cpa_disk  # noqa: E402
import emu  # noqa: E402
import gast_as  # noqa: E402
import gastlauf  # noqa: E402

SKIP = 77
Fehlt = cpa_disk.Fehlt
ANKER = "keys root\\r"          # first line of the part taken over from gastlauf.skript
FORMAT = " udos_ss77"           # format argument of the UDOS mounts; the CP/A scripts (C3) mount without it
FRIST = 3_000_000_000


def vorspann(arbeit):
    """Script lines from `gscreen "A>"` to the `login:` prompt."""
    z = ['gscreen "A>" 300000000',
         "keys M8KBOOT\\r",
         'gscreen "ready (r)" 300000000']
    for lw, img in (("A", "tmp"), ("B", "usr"), ("C", "root"), ("D", "d0")):
        z += ["eject " + lw, "mount %s %s/%s.hfe" % (lw, arbeit, img)]
    z += ["keys r",
          'gscreen "login:" 600000000',
          "g 3000000"]
    return z


def skript(arbeit, disketten, befehle, frist, schirm=False):
    """Debugger script.  Returns (script text, number of markers).  The part from `keys root` on is gastlauf.skript's."""
    text, nr = gastlauf.skript(arbeit, disketten, befehle, frist, schirm)
    zeilen = text.splitlines()
    n = zeilen.count(ANKER)
    if n != 1:
        raise RuntimeError("anchor %r occurs %d times in gastlauf.skript (need exactly 1)" % (ANKER, n))
    rest = [ln.replace(FORMAT, "") for ln in zeilen[zeilen.index(ANKER):]]
    kopf = ["# generated by tools/plus/cpa_lauf.py -- do not edit by hand"]
    return "\n".join(kopf + vorspann(arbeit) + rest) + "\n", nr


def _disks(arbeit, disketten, befehle, ausfuehrbar):
    """Image copies in `arbeit`: usr.hfe root.hfe, tmp.hfe (markers of the change steps + the final one), d<k>.hfe per source disk."""
    for ziel, quelle in gast_as.PLATTEN.items():
        if ziel != "boot.hfe":
            shutil.copyfile(gast_as.disk(quelle), os.path.join(arbeit, ziel))
    nmark = sum(2 if isinstance(b, tuple) else 1 for b in befehle)
    qa = os.path.join(arbeit, "qa")
    shutil.rmtree(qa, ignore_errors=True)
    os.makedirs(qa)
    with open(os.path.join(qa, "fertigs"), "w") as f:
        f.write("ENDES\n")
    nr = 0
    for b in befehle:
        nr += 1
        if isinstance(b, tuple):
            with open(os.path.join(qa, "fertig%d" % nr), "w") as f:
                f.write("END%d\n" % nr)
            nr += 1
    tmp = os.path.join(arbeit, "tmp.hfe")
    gastlauf._create(tmp, 200)
    gastlauf._put(tmp, [os.path.join(qa, f) for f in sorted(os.listdir(qa))])
    for k, d in enumerate(disketten):
        q = os.path.join(arbeit, "q%d" % k)
        shutil.rmtree(q, ignore_errors=True)
        os.makedirs(q)
        for n, t in d.items():
            with open(os.path.join(q, n), "wb") as f:
                f.write(t if isinstance(t, bytes) else t.encode("latin-1"))
        for i in range(1, nmark + 1):
            with open(os.path.join(q, "fertig%d" % i), "w") as f:
                f.write("END%d\n" % i)
        names = sorted(os.listdir(q))
        img = os.path.join(arbeit, "d%d.hfe" % k)
        gastlauf._create(img, len(names) + 40)
        gastlauf._put(img, [os.path.join(q, f) for f in names if not f.endswith(".fileinfo")])
        for n in names:
            if n.endswith(".fileinfo"):
                continue
            args = ["--mtime", gastlauf.MTIME_1987] + (["--mode", "0755"] if n in ausfuehrbar else [])
            gast_as._lauf([gast_as.disktool(), "attr", img, n] + args)
    return tmp


def lauf(arbeit, disketten, befehle, rueck, boot_hfe=None, ausfuehrbar=(), frist=FRIST, ausgabe=None, schirm=False):
    """Like gastlauf.lauf, but the guest boots over CP/A.  boot_hfe: CP/A boot disk (default: original kernel)."""
    if cpa.fehlt(werkzeug=True):
        raise Fehlt("emulator or CP/M tool chain")
    gast_as.pruefe_hilfsmittel()
    arbeit = os.path.abspath(arbeit)
    os.makedirs(arbeit, exist_ok=True)
    if boot_hfe is None:
        boot_hfe = cpa_disk.bootdiskette(arbeit)
    elif os.path.abspath(boot_hfe) != os.path.join(arbeit, "boot4.hfe"):
        shutil.copyfile(boot_hfe, os.path.join(arbeit, "boot4.hfe"))
    boot_hfe = os.path.join(arbeit, "boot4.hfe")
    tmp = _disks(arbeit, disketten, befehle, ausfuehrbar)
    sk, _ = skript(arbeit, disketten, befehle, frist, schirm)
    skf = os.path.join(arbeit, "lauf.dbg")
    with open(skf, "w") as f:
        f.write(sk)
    platte = os.path.join(arbeit, "platte.img.gz")      # GIDE hard disk: a copy, the run writes (--rw)
    shutil.copyfile(cpa.GIDE_PLATTE, platte)
    log = os.path.join(arbeit, "lauf.log")
    t0 = time.time()
    with open(log, "w") as lf:
        subprocess.run([emu.binary("k1520dbg"), "--em", "em256", "--rw", "--laderom", "ul4", "--gide=0xD0", "--gide-image", platte,
                        "--laufwerke", cpa_disk.LAUFWERKE, boot_hfe, "-x", skf],
                       stdout=lf, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL)
    if ausgabe is not None:
        ausgabe["dauer"] = time.time() - t0
        ausgabe["log"] = log
    holen = os.path.join(arbeit, "zurueck")
    shutil.rmtree(holen, ignore_errors=True)
    os.makedirs(holen)
    erg = {}
    for n in rueck:
        gast_as._lauf([gast_as.disktool(), "get", tmp, n, "--to", holen])
        pf = os.path.join(holen, n)
        erg[n] = open(pf, "rb").read() if os.path.exists(pf) else None
    return erg


def gast_befehle(arbeit, quellen, befehle, rueck, frist=FRIST, extra_dateien=None, ausgabe=None, boot_hfe=None, schirm=False,
                 ausfuehrbar=(), mnt="/mnt", quelle_hfe=None):
    """Like gast_as.gast_befehle: `quellen` on drive D (/mnt), `befehle` one after the other, `rueck` fetched from /tmp.
    Not supported (raise): mnt other than /mnt, quelle_hfe, extra_dateien."""
    if mnt != "/mnt" or quelle_hfe or extra_dateien:
        raise NotImplementedError("mnt/quelle_hfe/extra_dateien are not supported over CP/A")
    return lauf(arbeit, [quellen], list(befehle), rueck, boot_hfe=boot_hfe, ausfuehrbar=ausfuehrbar, frist=frist, ausgabe=ausgabe,
                schirm=schirm)


def boot(arbeit, kernel_bytes, frist=20_000_000_000):
    """Boot `kernel_bytes` over CP/A, run the work tests (gastbau.TESTS), judge them.  -> True when no failure."""
    import gastbau
    arbeit = os.path.abspath(arbeit)
    os.makedirs(arbeit, exist_ok=True)
    platte = cpa_disk.bootdiskette(arbeit, kernel=kernel_bytes)
    aus = {}
    erg = gast_befehle(os.path.join(arbeit, "boot"), gastbau.testdateien(arbeit), [b for _, b in gastbau.TESTS],
                       [n for n, _ in gastbau.TESTS], frist=frist, ausgabe=aus, boot_hfe=platte, schirm=True,
                       ausfuehrbar=["ps", "pstat"])
    print("boot test run time (wall clock): %.0f s, log %s" % (aus["dauer"], aus["log"]))
    return gastbau.auswerten(erg)


def probe(arbeit):
    """Plan 47 P1.0 acceptance over CP/A: two disks, change in between."""
    ausg = {}
    erg = lauf(arbeit, [{"a.txt": "AAA\n"}, {"b.txt": "BBB\n"}],
               ["cat a.txt >/tmp/a", ("wechsel", 1), "cat b.txt >/tmp/b", "ls /mnt >/tmp/l"],
               ["a", "b", "l"], ausgabe=ausg, schirm=True)
    print("run time %.0f s, log %s" % (ausg["dauer"], ausg["log"]))
    for n, v in erg.items():
        print("---", n, repr(v))
    l = (erg["l"] or b"").decode("latin-1").split()
    ok = erg["a"] == b"AAA\n" and erg["b"] == b"BBB\n" and "b.txt" in l and "a.txt" not in l
    print("ABNAHME", "ja" if ok else "NEIN")
    return 0 if ok else 1


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("cmd", choices=("probe", "boot"))
    ap.add_argument("--arbeit", required=True)
    ap.add_argument("--kernel", help="boot: kernel file (default: original mutos_1216)")
    a = ap.parse_args(argv)
    try:
        if cpa.fehlt(werkzeug=True):
            raise Fehlt("emulator or CP/M tool chain")
        if a.cmd == "probe":
            return probe(a.arbeit)
        kern = open(a.kernel, "rb").read() if a.kernel else cpa_disk.original_kernel(a.arbeit)
        return 0 if boot(a.arbeit, kern) else 1
    except (Fehlt, gast_as.Fehlt, cpa.Fehlt) as e:
        print("skip: missing", e)
        return SKIP


if __name__ == "__main__":
    sys.exit(main())
