#!/usr/bin/env python3
"""Build the V7 supplement disks v7erg1 / v7erg2 (plan 45 E6, doc/userspace/erg_e6.md).

Mount point in the guest: /v7 (bin/ and lib/ below it).  Contents come only from the finished builds
userspace/ergaenzung/NAME/work/bau/NAME.bin (run `python3 -I tools/userspace/erg.py bau NAME` for every program first)
and the lib files of tools/userspace/erg.py (LIBDATEIEN; libl.a is built in the guest by erg.libl_bauen()).
The split is in tools/disks/bauangaben_v7erg1.yaml / _v7erg2.yaml (keys `bin:` and `lib:`, space separated).
Date of all files: 1987-01-01 (so that `make` and `ls -l` behave like on the original disks).

  python3 -I tools/disks/bau_v7erg.py [--ziel-ordner disks/gebaut] [--ueberschreiben] [--nur 1|2] [--stage ORDNER]

Per disk one FM (MF3200) and one MFM (K5601) image: a5120_mutos8000_v7erg<N>_{fm,mfm}.hfe, built through
bau_aus_archiv.bauen from a staged archive folder (bauangaben.yaml, zylinder0.bin from the cmd archive, dateien/).
"""
import argparse
import os
import shutil
import sys
import tempfile
import zipfile

HIER = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HIER)
sys.path.insert(0, os.path.join(os.path.dirname(HIER), "userspace"))
sys.path.insert(0, os.path.join(os.path.dirname(HIER), "kernel"))
import bau_aus_archiv  # noqa: E402
import m8k  # noqa: E402

ERG = os.path.join(m8k.REPO, "userspace", "ergaenzung")
MTIME_1987 = 536457600      # 1987-01-01 00:00:00 UTC
SCHEIBEN = ("1", "2")


def bauangaben(n):
    """{key: value text} of tools/disks/bauangaben_v7erg<n>.yaml (one `key: value` per line, # comments)."""
    r = {}
    for z in open(os.path.join(HIER, "bauangaben_v7erg%s.yaml" % n)):
        z = z.split("#", 1)[0].strip() if z.lstrip().startswith("#") else z.rstrip("\n")
        if not z.strip():
            continue
        k, _, v = z.partition(":")
        r[k.strip()] = v.strip()
    return r


def fileinfo(name, art, mode):
    return ("# generated by tools/disks/bau_v7erg.py\nfs=wega_mutos\nname=%s\nart=%s\nmode=%07o\nuid=0\ngid=0\nnlink=1\n"
            "mtime=%d\natime=%d\nctime=%d\n" % (name, art, mode, MTIME_1987, MTIME_1987, MTIME_1987))


def inhalt(n, a):
    """[(guest path relative to /v7, bytes, mode)] of disk n."""
    import erg
    r = []
    for p in a.get("bin", "").split():
        pb = os.path.join(ERG, p, "work", "bau", p + ".bin")
        if not os.path.isfile(pb):
            raise SystemExit("%s: no build (python3 -I tools/userspace/erg.py bau %s)" % (p, p))
        r.append(("bin/" + p, open(pb, "rb").read(), 0o755))
    for l in a.get("lib", "").split():
        r.append(("lib/" + l, erg.libdatei(l), 0o755 if l == "diffh" else 0o644))
    return r


def stage(n, ordner):
    """Archive folder (bauangaben.yaml, zylinder0.bin, dateien/) for disk n; returns the number of data bytes."""
    a = bauangaben(n)
    dat = os.path.join(ordner, "dateien")
    os.makedirs(dat)
    gesamt = 0
    teile = inhalt(n, a)
    for d in sorted({os.path.dirname(p) for p, _, _ in teile}):
        os.makedirs(os.path.join(dat, d), exist_ok=True)
        with open(os.path.join(dat, d + ".fileinfo"), "w") as f:
            f.write(fileinfo(d, "d", 0o40755))
    for p, b, mode in teile:
        with open(os.path.join(dat, p), "wb") as f:
            f.write(b)
        with open(os.path.join(dat, p + ".fileinfo"), "w") as f:
            f.write(fileinfo(p, "-", 0o100000 | mode))
        gesamt += len(b)
    with zipfile.ZipFile(m8k.disk("best_cmd.zip")) as z:       # cylinder 0 (labels) as on the cmd disk
        with open(os.path.join(ordner, "zylinder0.bin"), "wb") as f:
            f.write(z.read("zylinder0.bin"))
    inodes = max(int(a["inodes"]), len(teile) + 8)
    with open(os.path.join(ordner, "bauangaben.yaml"), "w") as f:
        f.write("fs: %s\nfs_mfm: %s\ninodes: %d\nbloecke: %s\nzylinder0: zylinder0.bin\n"
                % (a["fs"], a["fs_mfm"], inodes, a["bloecke"]))
    return gesamt


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--ziel-ordner", default=m8k.FERTIG)
    ap.add_argument("--ueberschreiben", action="store_true")
    ap.add_argument("--nur", choices=SCHEIBEN)
    ap.add_argument("--stage", help="only stage the archive folder of --nur here (no image)")
    a = ap.parse_args(argv)
    for n in ([a.nur] if a.nur else SCHEIBEN):
        if a.stage:
            shutil.rmtree(a.stage, ignore_errors=True)
            print("v7erg%s: %d data bytes staged in %s" % (n, stage(n, a.stage), a.stage))
            continue
        for lw, suf in (("mf3200", "fm"), ("k5601", "mfm")):
            ziel = os.path.join(os.path.abspath(a.ziel_ordner), "a5120_mutos8000_v7erg%s_%s.hfe" % (n, suf))
            tmp = tempfile.mkdtemp(prefix="v7erg_")
            try:
                stage(n, os.path.join(tmp, "archiv"))
                bau_aus_archiv.bauen(os.path.join(tmp, "archiv"), ziel, ueberschreiben=a.ueberschreiben, laufwerke=lw)
            finally:
                shutil.rmtree(tmp, ignore_errors=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
