"""W7c: the initialized data tables of /usr/bin/as as C source (userspace/as/as_tabd.h) and their host-side proof.

  python3 -I tools/userspace/as_tabellen.py [--write]    # needs userspace/as/work/as.raw (pipeline.py holen as)

Tables (addresses in the original image, doc/userspace/wk_w7c.md): keyword 706E..7102 {name, token}, condition/flag/control register
7102..722E and 722E..729A {name, token, value}, mnemonic 729A..8310 (301 x 14 B) {name, 6 words}, then the scalar/pointer data 8310..8322,
then the string pool 8322..8A51 (names in table order, one pool per table, followed by one NUL byte each).
The proof (without any guest run): the emitted C text is parsed again and the data segment 706E..8A51 is rebuilt word for word,
with the pool addresses laid out as the original cc lays them (sequential; one NUL byte after each table's pool); every word must equal the image."""
import os, re, struct, sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RAW = os.path.join(REPO, "userspace", "as", "work", "as.raw")
OUT = os.path.join(REPO, "userspace", "as", "as_tabd.h")
BASE = 0x564C          # image address of data word 0 is TEXT size 22092 = 0x564C (image holds text + data)
KW, CT1, CT2, MN, VARS, POOL, END = 0x706E, 0x7102, 0x722E, 0x729A, 0x8310, 0x8322, 0x8A51

d = open(RAW, "rb").read()
W = lambda a: struct.unpack(">H", d[a:a + 2])[0]
S = lambda a: d[a:d.index(b"\0", a)].decode("ascii")


def cstr(s, last=False):
    # W7g: the last (empty) entry of every table is written "\\0": the original has one more NUL byte behind each pool
    # (wk_w7e.md); a two-byte string (NUL + terminator) gives exactly those bytes (Annahme: that is how the original wrote it)
    if last:
        return '"\\0"'
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"')


def emit():
    o = ["/* as_tabd.h: GENERATED by tools/userspace/as_tabellen.py from the original image (data 706E..8322).  Not V7 source text. */",
         "/* Not V7: reconstructed from the MUTOS binary.  Names of the arrays and members are invented (Annahme). */", ""]
    o.append("struct kwent kwtab[] = {")
    o += ["\t{ %s, %d }," % (cstr(S(W(a)), a == CT1 - 4), W(a + 2)) for a in range(KW, CT1, 4)]
    o.append("};")
    for nm, lo, hi in (("ctab1", CT1, CT2), ("ctab2", CT2, MN)):
        o.append("struct ctent %s[] = {" % nm)
        o += ["\t{ %s, 0x%X, %d }," % (cstr(S(W(a)), a == hi - 6), W(a + 2), W(a + 4)) for a in range(lo, hi, 6)]
        o.append("};")
    o.append("struct mnent mnem[] = {")
    for a in range(MN, VARS, 14):
        o.append("\t{ %s, { %s } }," % (cstr(S(W(a)), a == VARS - 14), ", ".join("0x%X" % W(a + k) for k in range(2, 14, 2))))
    o.append("};")
    return "\n".join(o) + "\n"


def rebuild(txt):
    """parse the emitted tables again and lay out the data exactly as the original cc does; returns bytes 706E..8322+pool."""
    kw = [(m[0], int(m[1])) for m in re.findall(r'\{ "([^"]*)", (\d+) \},', txt.split("struct ctent")[0])]
    ct = [[(m[0], int(m[1], 16), int(m[2])) for m in re.findall(r'\{ "([^"]*)", 0x([0-9A-F]+), (\d+) \},', blk)]
          for blk in txt.split("struct ctent")[1:3]]
    mn = [(m[0], [int(x, 16) for x in m[1].split(", ")]) for m in re.findall(r'\{ "([^"]*)", \{ ([^}]*) \} \},', txt.split("struct mnent")[1])]
    z = lambda n: "" if n == "\\0" else n     # the "\\0" sentinel is the empty name plus the pad NUL (rule below)
    names = [[n for n, _ in kw], [n for n, *_ in ct[0]], [n for n, *_ in ct[1]], [n for n, _ in mn]]
    # pool addresses: sequential from POOL, each table's pool padded to an even address
    ptr, a = [], POOL
    for grp in names:
        p = []
        for n in grp:
            n = z(n)
            p.append(a)
            a += len(n) + 1
        a += 1              # one NUL byte after each table's pool (measured: pools start 8322 83EB 84A9 850D, data after the last at 8A52)
        ptr.append(p)
    pool_end = a
    out = bytearray()
    for (n, t), p in zip(kw, ptr[0]):
        out += struct.pack(">HH", p, t)
    for blk, p in zip(ct, ptr[1:3]):
        for (n, t, v), q in zip(blk, p):
            out += struct.pack(">HHH", q, t, v)
    for (n, w), q in zip(mn, ptr[3]):
        out += struct.pack(">H6H", q, *w)
    pool = bytearray()
    for grp in names:
        for n in grp:
            n = z(n)
            pool += n.encode() + b"\0"
        pool += b"\0"      # same rule as above
    return bytes(out), bytes(pool), (len(kw), len(ct[0]), len(ct[1]), len(mn)), pool_end


def main():
    txt = emit()
    out, pool, cnt, pend = rebuild(txt)
    ok = out == d[KW:VARS] and pool == d[POOL:POOL + len(pool)]
    print("entries kw/ct1/ct2/mnem:", cnt, "| tables %d B equal: %s | pool %d B (to %04X) equal: %s"
          % (len(out), out == d[KW:VARS], len(pool), pend, pool == d[POOL:POOL + len(pool)]))
    print("scalar data 8310..8322:", " ".join("%04X" % W(a) for a in range(VARS, POOL, 2)))
    if "--write" in sys.argv:
        open(OUT, "w").write(txt)
    else:
        bad = [f for f, t in [("as_tabd.h", txt)]
               if os.path.isfile(os.path.join(os.path.dirname(OUT), f)) and open(os.path.join(os.path.dirname(OUT), f)).read() != t]
        if bad:
            print("differs from the generated text:", " ".join(bad))
            return 1
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
